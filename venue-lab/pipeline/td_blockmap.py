# The venue picker's Tokyo Dome block map: every block's outline, drawn round its own seats (the
# labels td_labels.py gives each seat), with the field and the building round them, written to
# src/three/venues/td-blocks.js. Run after td_build.py (and td_labels.py).
#
#   cd venue-lab/pipeline && python td_blockmap.py [--png check.png]
import sys, json, base64, os
import numpy as np, cv2

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'three', 'venues', 'td-blocks.js')
d = json.load(open(os.path.join(HERE, 'td_stands.json')))
names = d['blockNames']
BSC = 8.4   # the backscreen (no seats between F09 and F12), as dome.js

RES = 0.1                      # m a cell
X0, X1, Z0, Z1 = -150.0, 150.0, -200.0, 90.0
W, H = int((X1 - X0) / RES), int((Z1 - Z0) / RES)
def px(x, z): return np.c_[(x - X0) / RES, (z - Z0) / RES]

def seats(L):
    S = np.frombuffer(base64.b64decode(L['seats']), dtype=np.int16).reshape(-1, 4).astype(float)
    sk = L.get('seatScale') or 10
    Lb = np.frombuffer(base64.b64decode(L['labels']), dtype=np.int16).reshape(-1, 3)
    return S[:, 0] / sk, S[:, 1] / sk, Lb

blocks = []
for L in d['levels']:
    if 'labels' not in L: continue
    x, z, Lb = seats(L)
    keep = np.ones(len(x), bool)
    if L['name'] == 'F': keep &= np.degrees(np.abs(np.arctan2(x, -z))) >= BSC
    for b in np.unique(Lb[keep, 0]):
        m = keep & (Lb[:, 0] == b)
        if m.sum() < 3: continue
        nm = names[b]
        # (the seats as discs, run together along and across their rows, then the outline round them)
        img = np.zeros((H, W), np.uint8)
        for q in px(x[m], z[m]).round().astype(int): cv2.circle(img, tuple(q), int(0.45 / RES), 255, -1)
        k = int(1.1 / RES) * 2 + 1
        img = cv2.morphologyEx(img, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))
        cs, _ = cv2.findContours(img, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        polys = []
        for c in sorted(cs, key=cv2.contourArea, reverse=True):
            if cv2.contourArea(c) * RES * RES < 1.5: continue
            c = cv2.approxPolyDP(c, 0.25 / RES, True)[:, 0, :].astype(float)
            polys.append([[round(X0 + p[0] * RES, 1), round(Z0 + p[1] * RES, 1)] for p in c])
        if not polys: continue
        rows = Lb[m, 1]
        blocks.append({'n': nm, 'lv': L['name'], 'c': [round(float(x[m].mean()), 1), round(float(z[m].mean()), 1)],
                       'seats': int(m.sum()), 'rows': [int(rows.min()), int(rows.max())], 'p': polys})

def simp(poly, eps):
    c = np.array(poly, np.float32).reshape(-1, 1, 2)
    return [[round(float(a), 1), round(float(b), 1)] for a, b in cv2.approxPolyDP(c, eps, True)[:, 0, :]]
field = simp(d['field'][0][0], 0.3)
outer = simp(d['outer'][0][0], 0.5)

order = {'G': 0, 'A': 1, 'B': 2, 'F': 3, 'C': 4, 'D': 5, 'E': 6}
blocks.sort(key=lambda b: (order.get(b['lv'], 9), b['n']))
data = {'blocks': blocks, 'field': field, 'outer': outer}
s = json.dumps(data, separators=(',', ':'))
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// generated by venue-lab/pipeline/td_blockmap.py: the dome\'s blocks (data metres: x, z with home plate at 0, 0)\n')
    f.write('export const TD_BLOCKS = ' + s + ';\n')
print('blocks', len(blocks), 'KB', len(s) // 1024)
dup = {}
for b in blocks: dup[b['n']] = dup.get(b['n'], 0) + 1
print('names on more than one level:', {k: v for k, v in dup.items() if v > 1})
print('pieces > 1:', [(b['n'], len(b['p'])) for b in blocks if len(b['p']) > 1])

if '--png' in sys.argv:
    out = sys.argv[sys.argv.index('--png') + 1]
    S = 6
    img = np.full((int((Z1 - Z0) * S // 1), int((X1 - X0) * S // 1), 3), 255, np.uint8)
    P = lambda pts: np.array([[(p[0] - X0) * S, (p[1] - Z0) * S] for p in pts]).round().astype(np.int32)
    cv2.polylines(img, [P(field)], True, (120, 160, 120), 2)
    cv2.polylines(img, [P(outer)], True, (160, 160, 160), 2)
    rng = np.random.default_rng(3)
    for b in blocks:
        col = tuple(int(v) for v in rng.integers(60, 230, 3))
        for p in b['p']:
            cv2.fillPoly(img, [P(p)], col)
            cv2.polylines(img, [P(p)], True, (0, 0, 0), 1)
    for b in blocks:
        c = P([b['c']])[0]
        cv2.putText(img, b['n'], (int(c[0]) - 14, int(c[1]) + 4), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (0, 0, 0), 1, cv2.LINE_AA)
    open(out, "wb").write(cv2.imencode(".png", img)[1].tobytes())
    print('wrote', out)
