# The venue picker's Saitama Super Arena block map: every block (a door's seats: the labels
# ssa_labels.py gives each seat) outlined round its own seats, level by level, with the arena
# floor and the building round them, written to src/three/venues/ssa-blocks.js. Run after
# ssa_gen.py and ssa_labels.py.
#
#   cd venue-lab/pipeline && python ssa_blockmap.py [--png check.png]
import sys, json, base64, os
import numpy as np, cv2
from shapely.geometry import MultiPoint

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'three', 'venues', 'ssa-blocks.js')
d = json.load(open(os.path.join(HERE, 'ssa_stands.json')))
names = d['blockNames']

RES = 0.1                      # m a cell
X0, X1, Z0, Z1 = -80.0, 80.0, -75.0, 75.0
W, H = int((X1 - X0) / RES), int((Z1 - Z0) / RES)
def px(x, z): return np.c_[(x - X0) / RES, (z - Z0) / RES]

def seats(L):
    S = np.frombuffer(base64.b64decode(L['seats']), dtype=np.int16).reshape(-1, 4).astype(float)
    sk = L.get('seatScale') or 10
    Lb = np.frombuffer(base64.b64decode(L['labels']), dtype=np.int16).reshape(-1, 3)
    return S[:, 0] / sk, S[:, 1] / sk, Lb

blocks = []
for L in d['levels']:
    if 'labels' not in L: continue
    x, z, Lb = seats(L)
    keep = np.ones(len(x), bool)
    for b in np.unique(Lb[keep, 0]):
        m = keep & (Lb[:, 0] == b)
        if m.sum() < 3: continue
        nm = names[b]
        # the block's outline in straight lines: round its seats (half a seat out), the hull where the block is
        # convex (the list's blocks are boxes and wedges), else the seats run together and simplified
        pts = MultiPoint(list(zip(x[m], z[m])))
        hull = pts.convex_hull.buffer(0.42, join_style=2)
        body = pts.buffer(0.45, cap_style=3).buffer(0.6, join_style=2).buffer(-0.6, join_style=2)
        shape = hull if body.area > 0.9 * hull.area else body.simplify(0.35)
        geoms = getattr(shape, 'geoms', [shape])
        polys = [[[round(a, 1), round(b, 1)] for a, b in list(g.simplify(0.15).exterior.coords)[:-1]] for g in sorted(geoms, key=lambda g: -g.area) if g.area > 1.5]
        if not polys: continue
        rows = Lb[m, 1]
        blocks.append({'n': nm, 'lv': L['name'], 'c': [round(float(x[m].mean()), 1), round(float(z[m].mean()), 1)],
                       'seats': int(m.sum()), 'rows': [int(rows.min()), int(rows.max())], 'p': polys})

def simp(poly, eps):
    c = np.array(poly, np.float32).reshape(-1, 1, 2)
    return [[round(float(a), 1), round(float(b), 1)] for a, b in cv2.approxPolyDP(c, eps, True)[:, 0, :]]
# the arena floor between the 200 level's front rows (51 x 82 m), and the building's outline
field = [[-25.5, -41.0], [25.5, -41.0], [25.5, 41.0], [-25.5, 41.0]]
outer = simp(max((p[0] for p in d['outer']), key=lambda q: cv2.contourArea(np.array(q, np.float32))), 0.5)

order = {'200': 0, '300': 1, '300S': 2, '400': 3, '500': 4}
blocks.sort(key=lambda b: (order.get(b['lv'], 9), b['n']))
data = {'blocks': blocks, 'field': field, 'outer': outer}
s = json.dumps(data, separators=(',', ':'))
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// generated by venue-lab/pipeline/ssa_blockmap.py: the Saitama Super Arena\'s blocks (data metres about the floor\'s centre, -z the stage end)\n')
    f.write('export const SSA_BLOCKS = ' + s + ';\n')
print('blocks', len(blocks), 'KB', len(s) // 1024)
dup = {}
for b in blocks: dup[b['n']] = dup.get(b['n'], 0) + 1
print('names on more than one level:', {k: v for k, v in dup.items() if v > 1})
print('pieces > 1:', [(b['n'], len(b['p'])) for b in blocks if len(b['p']) > 1])

if '--png' in sys.argv:
    out = sys.argv[sys.argv.index('--png') + 1]
    S = 6
    img = np.full((int((Z1 - Z0) * S // 1), int((X1 - X0) * S // 1), 3), 255, np.uint8)
    P = lambda pts: np.array([[(p[0] - X0) * S, (p[1] - Z0) * S] for p in pts]).round().astype(np.int32)
    cv2.polylines(img, [P(field)], True, (120, 160, 120), 2)
    cv2.polylines(img, [P(outer)], True, (160, 160, 160), 2)
    rng = np.random.default_rng(3)
    for b in blocks:
        col = tuple(int(v) for v in rng.integers(60, 230, 3))
        for p in b['p']:
            cv2.fillPoly(img, [P(p)], col)
            cv2.polylines(img, [P(p)], True, (0, 0, 0), 1)
    for b in blocks:
        c = P([b['c']])[0]
        cv2.putText(img, b['n'], (int(c[0]) - 14, int(c[1]) + 4), cv2.FONT_HERSHEY_SIMPLEX, 0.38, (0, 0, 0), 1, cv2.LINE_AA)
    open(out, "wb").write(cv2.imencode(".png", img)[1].tobytes())
    print('wrote', out)
